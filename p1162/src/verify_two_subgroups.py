"""Independent check of src/two_subgroups.py, on explicit permutations; shares no code with it.

two_subgroups.py weights each subgroup of a Sylow subgroup by 1/s, with s, the
number of Sylow 2-subgroups containing it, read off as a count of maximal
chains of subgroups.  This script does not use that formula.  For every
fixed-point-free orbit type (b_1, ..., b_t), b_i in {2, 4, 8}, it

  1. builds the Sylow 2-subgroup R = prod_i Syl(Sym(O_i)) of the block
     stabiliser S = prod_i Sym(O_i) as explicit permutations of the k points,
     with its own generators, and lists the subgroups of R that are
     transitive on every block, by descent to maximal subgroups (the
     preimages of hyperplanes of M/Phi(M), with Phi(M) generated by squares);
  2. for every type with k <= --dedup-max, conjugates that list by a left
     transversal of R in S and counts the distinct subgroups, compared exactly
     as sorted lists of their elements -- every
     2-subgroup of S transitive on every block lies in one of the conjugates
     of R, so this is the count c(type) itself, with no weights at all;
  3. for every type, also counts c(type) with weights 1/s, where s is found by
     testing the subgroup against every Sylow 2-subgroup of every Sym(O_i),
     listed explicitly (315 of them for |O_i| = 8), not from a formula;
  4. classifies each subgroup by order and by Frattini-closure, computed
     literally: for each orbit O it generates Phi(H|O) from the squares of
     H restricted to O and tests whether it lies in H.

Then it sums over all orbit types of [n], fixed points included, with the
number of set partitions of each type counted by a recursion on the block
holding the first point, and compares the result with data/two_subgroups.json,
which it reads only at the end.  Exit status 0 only if every comparison holds.
"""

from __future__ import annotations

import argparse
import itertools
import json
import pathlib
import sys
import time
from collections import Counter
from fractions import Fraction
from functools import lru_cache

ROOT = pathlib.Path(__file__).resolve().parent.parent


def compose(p, q):
    """p after q."""
    return tuple(p[i] for i in q)


def inv(p):
    out = [0] * len(p)
    for i, x in enumerate(p):
        out[x] = i
    return tuple(out)


def generated(gens, k):
    e = tuple(range(k))
    seen = {e}
    todo = [e]
    while todo:
        p = todo.pop()
        for g in gens:
            q = compose(g, p)
            if q not in seen:
                seen.add(q)
                todo.append(q)
    return seen


def sylow_generators(points):
    """Generators of the Sylow 2-subgroup of Sym(points) that preserves the
    nest of consecutive pairs, quadruples, ... of the listed points."""
    b = len(points)
    gens = []
    size = 1
    while size < b:
        for start in range(0, b, 2 * size):  # swap the two halves of every block of size 2*size
            m = {}
            for j in range(size):
                m[points[start + j]] = points[start + size + j]
                m[points[start + size + j]] = points[start + j]
            gens.append(m)
        size *= 2
    return gens


def as_perm(m, k):
    return tuple(m.get(i, i) for i in range(k))


def bits(mask):
    while mask:
        low = mask & -mask
        yield low.bit_length() - 1
        mask ^= low


class Group:
    def __init__(self, gens, k):
        self.k = k
        self.el = sorted(generated(gens, k))
        self.ix = {p: i for i, p in enumerate(self.el)}
        self.e = self.ix[tuple(range(k))]
        self.tab = [[self.ix[compose(a, b)] for b in self.el] for a in self.el]

    def close(self, idxs):
        mask = 1 << self.e
        todo = [self.e]
        gs = list(set(idxs))
        while todo:
            x = todo.pop()
            row = self.tab[x]
            for g in gs:
                y = row[g]
                if not mask >> y & 1:
                    mask |= 1 << y
                    todo.append(y)
        return mask


def maximal(G: Group, M: int):
    els = list(bits(M))
    phi = G.close([G.tab[x][x] for x in els])
    phel = list(bits(phi))
    cos, reps = {}, []
    for x in els:
        if x not in cos:
            c = len(reps)
            reps.append(x)
            for f in phel:
                cos[G.tab[x][f]] = c
    vec = {cos[G.e]: 0}
    r = 0
    for x in reps:
        if cos[x] not in vec:
            for c, v in list(vec.items()):
                vec[cos[G.tab[reps[c]][x]]] = v | 1 << r
            r += 1
    for lam in range(1, 1 << r):
        K = 0
        for x in els:
            if bin(vec[cos[x]] & lam).count("1") % 2 == 0:
                K |= 1 << x
        yield K


def transitive_on(G: Group, K: int, block) -> bool:
    first = block[0]
    return {G.el[x][first] for x in bits(K)} == set(block)


def subgroups_transitive_on_blocks(G: Group, blocks):
    full = (1 << len(G.el)) - 1
    found, todo = {full}, [full]
    while todo:
        M = todo.pop()
        for K in maximal(G, M):
            if K not in found and all(transitive_on(G, K, B) for B in blocks):
                found.add(K)
                todo.append(K)
    return found


def frattini_closed(G: Group, H: int, k: int) -> bool:
    perms = [G.el[x] for x in bits(H)]
    hset = set(perms)
    seen = set()
    for i in range(k):
        if i in seen:
            continue
        orb = {p[i] for p in perms}
        seen |= orb
        if len(orb) == 1:
            continue
        squares = {tuple(q[q[j]] if j in orb else j for j in range(k)) for q in perms}
        if not generated(list(squares), k) <= hset:
            return False
    return True


def left_transversal(points, k, sylow_set):
    reps, covered = [], set()
    for img in itertools.permutations(points):
        g = list(range(k))
        for a, b in zip(points, img):
            g[a] = b
        g = tuple(g)
        if g in covered:
            continue
        reps.append(g)
        for s in sylow_set:
            covered.add(compose(g, s))
    return reps


@lru_cache(maxsize=None)
def sylows_of_block(b):
    """Every Sylow 2-subgroup of Sym({0..b-1}), as a frozenset of permutations of b points."""
    pts = list(range(b))
    R = generated([as_perm(m, b) for m in sylow_generators(pts)], b)
    out = set()
    for g in left_transversal(pts, b, R):
        gi = inv(g)
        out.add(frozenset(compose(compose(g, s), gi) for s in R))
    return list(out), R


def set_partitions_of_type(sizes: tuple[int, ...]) -> int:
    """Set partitions of [sum(sizes)] with these block sizes: choose the block of the first point."""

    @lru_cache(maxsize=None)
    def rec(ms: tuple[int, ...]) -> int:
        k = sum(ms)
        if k == 0:
            return 1
        tot = 0
        for b in set(ms):
            rest = list(ms)
            rest.remove(b)
            c = 1
            for i in range(b - 1):  # C(k-1, b-1)
                c = c * (k - 1 - i) // (i + 1)
            tot += c * rec(tuple(sorted(rest)))
        return tot

    return rec(tuple(sorted(sizes)))


def orbit_types(k, parts):
    if k == 0:
        yield ()
        return
    for b in parts:
        if b <= k:
            for rest in orbit_types(k - b, [p for p in parts if p <= b]):
                yield (b,) + rest


def count_type(sizes, dedup: bool):
    k = sum(sizes)
    blocks, pos = [], 0
    for b in sizes:
        blocks.append(list(range(pos, pos + b)))
        pos += b
    gens = []
    for B in blocks:
        gens += [as_perm(m, k) for m in sylow_generators(B)]
    G = Group(gens, k)
    subs = subgroups_transitive_on_blocks(G, blocks)

    # weighted count, s found by testing every Sylow subgroup of every block
    sylows = {b: sylows_of_block(b)[0] for b in set(sizes)}
    n2 = 1
    for b in sizes:
        n2 *= len(sylows[b])
    weighted = Counter()
    info = {}
    for H in subs:
        perms = [G.el[x] for x in bits(H)]
        s = 1
        for B in blocks:
            proj = {tuple(p[B[0] + j] - B[0] for j in range(len(B))) for p in perms}
            s *= sum(1 for Q in sylows[len(B)] if proj <= Q)
        fc = frattini_closed(G, H, k)
        info[H] = fc
        weighted[(len(perms), fc)] += Fraction(n2, s)
    assert all(v.denominator == 1 for v in weighted.values()), "a weighted count is not an integer"
    weighted = Counter({key: int(v) for key, v in weighted.items()})

    distinct = None
    if dedup:
        trans = []
        for B in blocks:
            Rb = sylows_of_block(len(B))[1]
            local = left_transversal(list(range(len(B))), len(B), Rb)
            trans.append([tuple(list(range(B[0])) + [B[0] + g[j] for j in range(len(B))] + list(range(B[-1] + 1, k))) for g in local])
        # Conjugation by S keeps the order, the FC status and the order of the group induced on
        # each block, so distinct subgroups are collected one class of these invariants at a
        # time, which bounds the memory.  Within a class a subgroup is keyed exactly, by the
        # sorted list of its elements packed into bytes (4 bits per point), not by a hash.
        conj = []
        for gs in itertools.product(*trans):
            g = tuple(range(k))
            for h in gs:
                g = compose(h, g)
            conj.append((g, inv(g)))
        width = (4 * k + 7) // 8

        def code(p):
            c = 0
            for i, x in enumerate(p):
                c |= x << (4 * i)
            return c

        classes = {}
        for H in subs:
            perms = [G.el[x] for x in bits(H)]
            proj = tuple(len({tuple(p[j] for j in B) for p in perms}) for B in blocks)
            classes.setdefault((len(perms), info[H], proj), []).append(perms)
        distinct = Counter()
        for (order, fc, _), members in classes.items():
            seen = set()
            for perms in members:
                for g, gi in conj:
                    seen.add(b"".join(c.to_bytes(width, "little") for c in sorted(code(compose(compose(g, p), gi)) for p in perms)))
            distinct[(order, fc)] += len(seen)
    return weighted, distinct, len(subs)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--n-max", type=int, default=15)
    ap.add_argument("--dedup-max", type=int, default=12, help="largest k whose types are also counted by explicit conjugation")
    ap.add_argument("--census", type=pathlib.Path, default=ROOT / "data" / "two_subgroups.json")
    ap.add_argument("--out", type=pathlib.Path, default=ROOT / "results" / "verify_two_subgroups.json")
    args = ap.parse_args()
    t0 = time.time()
    failures = []

    def check(ok, label):
        print(f"  [{'pass' if ok else 'FAIL'}] {label}")
        if not ok:
            failures.append(label)

    kmax = args.n_max - args.n_max % 2
    c = {(): Counter({(1, True): 1})}
    listed = {}
    print("== orbit types: subgroups of the Sylow subgroup transitive on every block ==")
    for k in range(2, kmax + 1, 2):
        for sizes in orbit_types(k, [8, 4, 2]):
            t1 = time.time()
            w, d, nl = count_type(sizes, k <= args.dedup_max)
            c[sizes] = w
            listed[",".join(map(str, sizes))] = nl
            msg = f"{str(sizes):16s} {nl:7d} listed, c = {sum(w.values())}"
            if d is not None:
                check(d == w, f"type {sizes}: {sum(d.values())} distinct conjugates, by order and FC, = the count weighted by 1/s")
            print(f"  {msg}  ({time.time() - t1:.1f}s)")

    rows = {}
    for n in range(1, args.n_max + 1):
        tot = Counter()
        for sizes in orbit_types(n, [8, 4, 2, 1]):
            moved = tuple(b for b in sizes if b > 1)
            mult = set_partitions_of_type(sizes)
            for key, v in c[moved].items():
                tot[key] += mult * v
        rows[n] = {
            "total": sum(tot.values()),
            "fc": sum(v for (o, fc), v in tot.items() if fc),
            "by_order": {str(o): sum(v for (o2, _), v in tot.items() if o2 == o) for o in sorted({o for o, _ in tot})},
            "fc_by_order": {str(o): sum(v for (o2, fc), v in tot.items() if o2 == o and fc) for o in sorted({o for o, fc in tot if fc})},
        }

    print(f"\n== against {args.census.name} ==")
    stored = json.loads(args.census.read_text())["two_subgroups"]
    for n, r in rows.items():
        s = stored.get(str(n))
        ok = s is not None and all(s[key] == r[key] for key in ("total", "fc", "by_order", "fc_by_order"))
        check(ok, f"n={n}: {r['total']} 2-subgroups, {r['fc']} FC, by order, equal two_subgroups.py")

    out = {
        "description": "Independent count of the 2-subgroups of S_n (src/verify_two_subgroups.py)",
        "n_max": args.n_max,
        "dedup_max": args.dedup_max,
        "listed_per_type": listed,
        "two_subgroups": {str(n): r for n, r in rows.items()},
        "match": not failures,
        "seconds": round(time.time() - t0, 1),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(out, indent=1) + "\n")
    shown = args.out.resolve().relative_to(ROOT) if args.out.resolve().is_relative_to(ROOT) else args.out
    print(f"\nwrote {shown}  ({time.time() - t0:.1f}s)")
    print(f"{len(failures)} failed" if failures else "all checks passed")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
