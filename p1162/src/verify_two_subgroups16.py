"""Independent recount of data/two_subgroups16.json; shares no code with census16.c or two_subgroups16.py.

two_subgroups16.py gets the orbit types of 16 points from census16.c (C, descent inside R with
Sylow numbers from block flags found by minimal-block closures) and t(k), k <= 14, from
data/two_subgroups.json.  This script recounts all of it another way:

  1. every orbit type of 16 points with blocks of size <= 8 is counted by count_type() of
     two_subgroups.py (numpy, Sylow numbers from maximal chains of subgroups), the code already
     checked against verify_two_subgroups.py for n <= 15;
  2. the type (16) is not enumerated inside R_16 at all.  A transitive H <= R_16 swaps the two
     halves {0..7} and {8..15}, which form a block system of R_16, so K = H n (R_8 x R_8) has
     index 2 in H and is transitive on both halves: K is one of the subgroups of type (8, 8)
     listed in step 1.  Conversely H = K u tK for t = (a, b)sigma in the swap coset with
     t K t^-1 = K and t^2 in K.  So for every K of type (8, 8) the cosets tK are found by testing
     every t (after a filter on the two projections), and H is assembled as explicit
     permutations of 16 points;
  3. s_16(H), the number of Sylow 2-subgroups of S_16 containing H, is the number of H-invariant
     nests of partitions into blocks of sizes 2 < 4 < 8, counted by testing the literal
     definition of a block (h(B) = B or h(B) n B empty for every element h of H) on candidate
     sets, each built from a block one level down; d(H) from Phi(H) generated by all squares;
  4. no weights: the subgroups of order 16 in step 2 are the regular ones.  They are sorted into
     isomorphism classes by explicit isomorphisms, |Aut G| is counted by brute force, and the
     number of regular subgroups of S_16 is sum_G 16!/(16 |Aut G|), the normaliser of a regular
     G being its holomorph; this must equal the weighted count of order 16 from step 3;
  5. t(k) for k <= 15 is the inverse binomial transform of the rows in
     results/verify_two_subgroups.json, the explicit-permutation recount of n <= 15, which must
     vanish at odd k; with t(16) from steps 1-3 that gives T(16) and T(17).

data/two_subgroups16.json is read only at the end, to compare.  Exit status 0 only if every
comparison holds.  Runs the orbit types in parallel (--jobs, default 4); type (8, 8) needs
about 3 GB for the multiplication table of R_8 x R_8.
"""

from __future__ import annotations

import argparse
import json
import multiprocessing as mp
import pathlib
import sys
import time
from collections import Counter, defaultdict
from fractions import Fraction
from math import comb, factorial

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

SIGMA = np.array(list(range(8, 16)) + list(range(8)))


def multi_orbit_types() -> list[tuple[int, ...]]:
    def rec(k, top):
        if k == 0:
            yield ()
            return
        for b in (8, 4, 2):
            if b <= min(k, top):
                for rest in rec(k - b, b):
                    yield (b,) + rest

    return list(rec(16, 8))


# ------------------------------------------------- step 3: literal blocks and Phi


def is_block(perms: np.ndarray, S: list[int]) -> bool:
    inside = np.zeros(16, dtype=bool)
    inside[S] = True
    v = inside[perms[:, S]]
    return bool((v.all(axis=1) | ~v.any(axis=1)).all())


def system_of(perms: np.ndarray, S: list[int]) -> set[frozenset]:
    return {frozenset(row) for row in perms[:, S].tolist()}


def sylow_count16(perms: np.ndarray) -> int:
    """Nests B2 < B4 < B8 of blocks containing the point 0, by the literal definition."""
    b2 = [frozenset((0, j)) for j in range(1, 16) if is_block(perms, [0, j])]
    ways4 = Counter()
    for B in b2:
        for C in system_of(perms, sorted(B)):
            if C != B:
                U = B | C
                if U not in ways4 and is_block(perms, sorted(U)):
                    ways4[U] = sum(1 for X in b2 if X <= U)
    s = 0
    seen8 = set()
    for B in ways4:
        for C in system_of(perms, sorted(B)):
            if C != B:
                U = B | C
                if U not in seen8 and is_block(perms, sorted(U)):
                    seen8.add(U)
                    s += sum(w for X, w in ways4.items() if X <= U)
    return s


# ------------------------------------------------- step 2: the extensions of K


class Extensions:
    """Visitor for the (8, 8) list: assembles every transitive H <= R_16 from its K."""

    def __init__(self):
        self.tally = Counter()  # (log2|H|, s_16, d) -> number of H
        self.regular = []
        self.ready = False

    def setup(self, A):
        from two_subgroups import frattini_coordinates

        self.fc = frattini_coordinates
        F = A.factors[0]
        assert A.factors[1] == F and len(F) == 128
        idx = {p: i for i, p in enumerate(F)}
        self.M8 = np.array([[idx[tuple(a[j] for j in c)] for c in F] for a in F], dtype=np.int64)  # a after c
        self.I8 = np.array([idx[tuple(sorted(range(8), key=lambda j: p[j]))] for p in F], dtype=np.int64)
        ar = np.arange(128)
        self.CONJ = self.M8[self.M8[ar[:, None], ar[None, :]], self.I8[ar][:, None]]  # CONJ[a, y] = a y a^-1
        P8 = np.array(F, dtype=np.int64)
        e = np.arange(A.N)
        self.c0, self.c1 = A.comp[0], A.comp[1]
        assert (self.c0 + 128 * self.c1 == e).all()
        self.BASE = np.concatenate([P8[self.c0], P8[self.c1] + 8], axis=1)  # (x, y) as a permutation of 16 points
        self.A = A
        self.ready = True

    def __call__(self, A, els):
        if not self.ready:
            self.setup(A)
        M8, CONJ = self.M8, self.CONJ
        x, y = self.c0[els], self.c1[els]
        memK = np.zeros(A.N, dtype=bool)
        memK[els] = True
        coord, r, _ = self.fc(A, els)
        cv = coord[els]
        gens = np.array([els[cv == 1 << j][0] for j in range(r)])  # Burnside basis: these generate K
        gx, gy = self.c0[gens], self.c1[gens]
        K1 = np.zeros(128, dtype=bool)
        K1[x] = True
        K2 = np.zeros(128, dtype=bool)
        K2[y] = True
        # t = (a, b) sigma:  t (x, y) t^-1 = (a y a^-1, b x b^-1),  t^2 = (ab, ba)
        ac = np.nonzero(K1[CONJ[:, gy]].all(axis=1))[0]
        bc = np.nonzero(K2[CONJ[:, gx]].all(axis=1))[0]
        if len(ac) == 0 or len(bc) == 0:
            return
        a, b = np.repeat(ac, len(bc)), np.tile(bc, len(ac))
        ok = memK[M8[a, b] + 128 * M8[b, a]]
        for j in range(r):
            ok &= memK[CONJ[a, gy[j]] + 128 * CONJ[b, gx[j]]]
        a, b = a[ok], b[ok]
        if len(a) == 0:
            return
        left = dict.fromkeys((a + 128 * b).tolist())
        Kperms = self.BASE[els]
        sqK = A.sq[els]
        while left:
            code = next(iter(left))
            a0, b0 = code % 128, code // 128
            # t (x, y) = (a, b)(y, x) sigma = (a y, b x) sigma
            ca, cb = M8[a0, y], M8[b0, x]
            coset = ca + 128 * cb
            for c in coset.tolist():
                del left[c]  # KeyError here would mean the valid t do not form cosets of K
            Hperms = np.concatenate([Kperms, self.BASE[coset][:, SIGMA]])
            assert len(np.unique(Hperms[:, 0])) == 16
            # squares: those of K, and ((a, b) sigma)^2 = (ab, ba)
            squares = np.unique(np.concatenate([sqK, M8[ca, cb] + 128 * M8[cb, ca]]))
            phi = np.zeros(A.N, dtype=bool)
            phi[squares] = True
            frontier = squares
            while len(frontier):
                new = np.unique(A.mul[np.ix_(frontier, squares)].ravel())
                new = new[~phi[new]]
                phi[new] = True
                frontier = new
            order = 2 * len(els)
            d = (order // int(phi.sum())).bit_length() - 1
            assert order == int(phi.sum()) << d
            self.tally[(order.bit_length() - 1, sylow_count16(Hperms), d)] += 1
            if order == 16:
                self.regular.append(Hperms.astype(np.int8))


# ------------------------------------------------- step 4: regular subgroups, no weights


def cayley(perms: np.ndarray):
    rows = [tuple(p) for p in perms.tolist()]
    ix = {p: i for i, p in enumerate(rows)}
    tab = [[ix[tuple(p[j] for j in q)] for q in rows] for p in rows]
    e = ix[tuple(range(16))]
    return tab, e


def element_orders(tab, e):
    out = []
    for g in range(len(tab)):
        k, x = 1, g
        while x != e:
            x, k = tab[x][g], k + 1
        out.append(k)
    return out


def gen_tuple(tab, e):
    """A generating tuple chosen greedily, and the words (BFS tree) expressing every element in it."""
    n = len(tab)
    gens = []
    while True:
        span = {e}
        todo = [e]
        while todo:
            u = todo.pop()
            for g in gens:
                v = tab[u][g]
                if v not in span:
                    span.add(v)
                    todo.append(v)
        if len(span) == n:
            return gens
        gens.append(min(set(range(n)) - span))


def extend(tabA, eA, gens, tabB, eB, imgs):
    """The homomorphism A -> B with gens -> imgs, if it exists and is bijective."""
    phi = {eA: eB}
    todo = [eA]
    while todo:
        u = todo.pop()
        for g, h in zip(gens, imgs):
            v, w = tabA[u][g], tabB[phi[u]][h]
            if v in phi:
                if phi[v] != w:
                    return None
            else:
                phi[v] = w
                todo.append(v)
    if len(set(phi.values())) != len(tabA):
        return None
    for u in range(len(tabA)):  # a check on all products, not only on the generators
        for v in range(len(tabA)):
            if phi[tabA[u][v]] != tabB[phi[u]][phi[v]]:
                return None
    return phi


def isomorphic(GA, GB) -> bool:
    (tabA, eA, oA), (tabB, eB, oB) = GA, GB
    gens = gen_tuple(tabA, eA)
    cands = [[h for h in range(len(tabB)) if oB[h] == oA[g]] for g in gens]

    def rec(i, imgs):
        if i == len(gens):
            return extend(tabA, eA, gens, tabB, eB, imgs) is not None
        return any(rec(i + 1, imgs + [h]) for h in cands[i])

    return rec(0, [])


def automorphisms(G) -> int:
    tab, e, o = G
    gens = gen_tuple(tab, e)
    cands = [[h for h in range(len(tab)) if o[h] == o[g]] for g in gens]
    count = 0

    def rec(i, imgs):
        nonlocal count
        if i == len(gens):
            count += extend(tab, e, gens, tab, e, imgs) is not None
            return
        for h in cands[i]:
            rec(i + 1, imgs + [h])

    rec(0, [])
    return count


def regular_count(groups: list[np.ndarray]) -> tuple[int, list[dict]]:
    classes = []  # (invariant, G, members)
    for perms in groups:
        tab, e = cayley(perms)
        o = element_orders(tab, e)
        centre = sum(1 for g in range(16) if all(tab[g][h] == tab[h][g] for h in range(16)))
        inv = (tuple(sorted(o)), centre)
        G = (tab, e, o)
        for c in classes:
            if c[0] == inv and isomorphic(c[1], G):
                c[2] += 1
                break
        else:
            classes.append([inv, G, 1])
    total = 0
    info = []
    for inv, G, members in classes:
        aut = automorphisms(G)
        total += Fraction(factorial(16), 16 * aut)
        info.append({"element_orders": dict(sorted(Counter(inv[0]).items())), "centre": inv[1], "aut": aut, "in_R16": members})
    assert total.denominator == 1
    return int(total), info


# ------------------------------------------------- the workers


def work(blocks):
    from two_subgroups import count_type, sylow_weights

    t0 = time.time()
    sw = {b: sylow_weights(b) for b in (2, 4, 8)}
    ext = Extensions() if blocks == (8, 8) else None
    c, listed = count_type(blocks, sw, visit=ext)
    out = {"blocks": blocks, "c": {k: v for k, v in c.items()}, "listed": listed, "seconds": round(time.time() - t0, 1)}
    if ext is not None:
        out["tally"] = dict(ext.tally)
        out["regular"] = ext.regular
    return out


def set_partitions(sizes) -> int:
    k = sum(sizes)
    den = 1
    for b in set(sizes):
        m = sizes.count(b)
        den *= factorial(b) ** m * factorial(m)
    return factorial(k) // den


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--small", type=pathlib.Path, default=ROOT / "results" / "verify_two_subgroups.json")
    ap.add_argument("--census", type=pathlib.Path, default=ROOT / "data" / "two_subgroups16.json")
    ap.add_argument("--out", type=pathlib.Path, default=ROOT / "results" / "verify_two_subgroups16.json")
    args = ap.parse_args()
    t0 = time.time()
    failures = []

    def check(ok, label):
        print(f"  [{'pass' if ok else 'FAIL'}] {label}", flush=True)
        if not ok:
            failures.append(label)

    types = sorted(multi_orbit_types(), key=lambda t: -(2 ** sum(b - 1 for b in t)) * len(t))
    types.remove((8, 8))
    types.insert(0, (8, 8))
    print(f"== {len(types)} orbit types with blocks <= 8, by count_type() of two_subgroups.py ==", flush=True)
    with mp.get_context("fork").Pool(args.jobs) as pool:
        results = {}
        for r in pool.imap_unordered(work, types):
            results[r["blocks"]] = r
            print(f"  {str(r['blocks']):26s} {r['listed']:8d} listed, c = {int(sum(r['c'].values()))}  ({r['seconds']:.0f}s)", flush=True)

    per_type = {}
    for t in types:
        r = results[t]
        check(all(v.denominator == 1 for v in r["c"].values()), f"type {t}: every weighted sum is an integer")
        per_type[",".join(map(str, t))] = {
            "listed_in_R": r["listed"],
            "per_partition": int(sum(r["c"].values())),
            "per_partition_fc": int(sum(v for (j, fc, ea), v in r["c"].items() if fc)),
            "partitions": set_partitions(list(t)),
            "seconds": r["seconds"],
        }

    print("\n== type (16): the extensions H = K u tK of the (8, 8) list ==", flush=True)
    tally = results[(8, 8)]["tally"]
    n2 = factorial(16) // 2**15
    listed_by_order, by_order, s_listed, d_listed, by_d = Counter(), defaultdict(Fraction), Counter(), Counter(), defaultdict(Fraction)
    for (j, s, d), cnt in tally.items():
        listed_by_order[j] += cnt
        by_order[j] += Fraction(n2 * cnt, s)
        by_d[d] += Fraction(n2 * cnt, s)
        s_listed[s] += cnt
        d_listed[d] += cnt
    check(all(v.denominator == 1 for v in by_order.values()), "type (16): every weighted sum is an integer")
    trans = {
        "listed": sum(listed_by_order.values()),
        "listed_by_log2_order": {str(j): listed_by_order[j] for j in sorted(listed_by_order)},
        "total": int(sum(by_order.values())),
        "by_order": {str(2**j): int(by_order[j]) for j in sorted(by_order)},
        "by_d": {str(d): int(by_d[d]) for d in sorted(by_d)},
        "listed_by_s": {str(s): s_listed[s] for s in sorted(s_listed)},
        "listed_by_d": {str(d): d_listed[d] for d in sorted(d_listed)},
    }
    print(f"  {trans['listed']} transitive subgroups of R_16; {trans['total']} transitive 2-subgroups of S_16", flush=True)
    t1 = time.time()
    reg_total, reg_info = regular_count(results[(8, 8)]["regular"])
    print(f"  regular subgroups: {len(reg_info)} isomorphism classes, sum 16!/(16|Aut G|) = {reg_total}  ({time.time() - t1:.0f}s)", flush=True)
    check(reg_total == trans["by_order"]["16"], f"no weights: the regular subgroups of S_16 number sum_G 16!/(16|Aut G|) = {reg_total} = the weighted count of order 16")

    print("\n== T(16), T(17) from the n <= 15 recount and t(16) ==", flush=True)
    small = json.loads(args.small.read_text())
    if not small.get("match") or small.get("n_max", 0) < 15:
        check(False, f"{args.small.name} must be a passing recount to n = 15")
        return 1
    rows = {0: Counter({(1, True): 1})}
    for n, r in small["two_subgroups"].items():
        C = Counter()
        for o, v in r["by_order"].items():
            C[(int(o), True)] += r["fc_by_order"].get(o, 0)
            C[(int(o), False)] += v - r["fc_by_order"].get(o, 0)
        rows[int(n)] = C
    t = {}
    for k in range(16):
        C = Counter()
        for j in range(k + 1):
            for key, v in rows[j].items():
                C[key] += (-1) ** (k - j) * comb(k, j) * v
        t[k] = Counter({key: v for key, v in C.items() if v})
    check(all(not t[k] for k in range(1, 16, 2)), "the inverse binomial transform of the n <= 15 recount vanishes at every odd k")
    t16 = Counter()
    for tname, v in per_type.items():
        for (j, fc, ea), c in results[tuple(map(int, tname.split(",")))]["c"].items():
            t16[(2**j, fc)] += v["partitions"] * int(c)
    for o, v in trans["by_order"].items():
        t16[(int(o), True)] += v
    t[16] = t16
    mine = {}
    for n in (16, 17):
        C = Counter()
        for k, tk in t.items():
            for key, v in tk.items():
                C[key] += comb(n, k) * v
        mine[n] = {
            "total": sum(C.values()),
            "fc": sum(v for (o, fc), v in C.items() if fc),
            "by_order": {str(o): sum(v for (o2, _), v in C.items() if o2 == o) for o in sorted({o for o, _ in C})},
            "fc_by_order": {str(o): sum(v for (o2, fc), v in C.items() if o2 == o and fc) for o in sorted({o for o, fc in C if fc})},
        }
        print(f"  n={n}: {mine[n]['total']} 2-subgroups, {mine[n]['fc']} FC", flush=True)

    print(f"\n== against {args.census.name} ==", flush=True)
    stored = json.loads(args.census.read_text())
    for name, v in per_type.items():
        s = stored["types"].get(name, {})
        check(all(s.get(key) == v[key] for key in ("listed_in_R", "per_partition", "per_partition_fc", "partitions")), f"type ({name}): {v['listed_in_R']} listed, c = {v['per_partition']}, c_FC = {v['per_partition_fc']}, equal census16")
    st = stored["transitive16"]
    check(stored["types"]["16"]["listed_by_log2_order"] == trans["listed_by_log2_order"], f"type (16): {trans['listed']} subgroups of R_16, by order, equal census16")
    for key in ("total", "by_order", "listed_by_s", "listed_by_d", "by_d"):
        check(st[key] == trans[key], f"type (16): {key} equals census16")
    for n in (16, 17):
        s = stored["two_subgroups"][str(n)]
        check(all(s[key] == mine[n][key] for key in ("total", "fc", "by_order", "fc_by_order")), f"n={n}: {mine[n]['total']} 2-subgroups, {mine[n]['fc']} FC, by order, equal two_subgroups16.py")

    out = {
        "description": "Independent recount of the 2-subgroups of S_16 and S_17 (src/verify_two_subgroups16.py)",
        "types": per_type,
        "transitive16": trans,
        "regular16": {"classes": reg_info, "total": reg_total},
        "two_subgroups": {str(n): r for n, r in mine.items()},
        "match": not failures,
        "seconds": round(time.time() - t0, 1),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(out, indent=1) + "\n")
    shown = args.out.resolve().relative_to(ROOT) if args.out.resolve().is_relative_to(ROOT) else args.out
    print(f"\nwrote {shown}  ({time.time() - t0:.1f}s)")
    print(f"{len(failures)} failed" if failures else "all checks passed")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
